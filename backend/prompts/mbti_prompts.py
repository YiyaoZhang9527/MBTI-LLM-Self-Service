"""
MBTI分析Prompt管理模块
集中管理所有MBTI相关的分析Prompt
"""


class MBTIPrompts:
    """MBTI分析Prompt类"""

    @staticmethod
    def get_system_prompt() -> str:
        """获取系统Prompt"""
        return """你是一位专业的MBTI人格分析师和心理咨询师，具有丰富的职业规划经验。

你的任务是根据用户提供的MBTI测试数据，生成一份专业、个性化且富有洞察力的人格分析报告。

分析要求：
1. **专业性**：基于MBTI理论和认知功能进行科学分析
2. **个性化**：结合用户的答题行为数据进行针对性分析
3. **实用性**：提供具体的职业发展建议和成长策略
4. **正能量**：以鼓励和启发的方式指出发展空间
5. **结构化**：按照给定的模板格式生成Markdown报告

分析重点：
- 基于答题模式分析决策特征和认知风格
- 结合停留时间和修改次数判断决策自信度
- 根据答案一致性分析人格特质的稳定性
- 提供具体的职业适配建议和团队角色定位
- 给出可执行的个人成长策略"""

    @staticmethod
    def get_analysis_prompt() -> str:
        """获取主要分析Prompt"""
        return """请基于以下MBTI测试数据，为用户生成一份深度的人格分析报告。

**分析框架要求**：

## 一、MBTI类型基础分析
- 根据测试结果确定MBTI类型和各维度倾向性
- 分析百分比分布的意义和特质稳定性
- 解释认知功能栈（主导功能、辅助功能等）

## 二、答题行为深度分析
- **决策速度分析**：基于平均停留时间（<3秒=快速型，3-8秒=深思熟虑型，>8秒=谨慎型）
- **决策稳定性分析**：基于修改次数（0-1次=果断型，2-3次=犹豫型，>3次=不确定型）
- **认知一致性分析**：同类维度题目的答案一致性
- **关键模式识别**：高确定性/高不确定性区域反映的人格特质

## 三、职业发展与适配
- **最适合的工作环境**：基于MBTI类型和行为分析
- **突出职业能力**：识别核心竞争力和优势领域
- **团队角色定位**：在团队中的自然角色和贡献方式
- **潜在职业挑战**：需要注意的发展领域

## 四、人际关系与沟通
- **沟通风格特征**：基于答题行为的沟通偏好
- **最佳协作模式**：与不同人格类型的协作策略
- **冲突处理方式**：压力情境下的应对模式
- **关系发展建议**：改善人际关系的具体方法

## 五、个人成长策略
- **认知盲区识别**：需要关注和发展的心理区域
- **成长路径规划**：短中长期发展目标
- **压力管理方法**：基于人格特质的压力应对策略
- **潜能开发建议**：如何发挥潜在优势

**输出格式要求**：
- 使用Markdown格式
- 结构清晰，层次分明
- 语言专业但不晦涩
- 包含具体可执行的建议
- 体现个性化分析特色

**特别提醒**：
- 避免刻板印象和过度概括
- 结合具体的答题数据进行分析
- 保持积极正面的导向
- 建议要具体可执行"""

    @staticmethod
    def get_quick_analysis_prompt() -> str:
        """获取快速分析Prompt"""
        return """基于提供的MBTI测试数据，生成一份简洁但专业的人格分析报告。

核心要求：
1. **类型判断**：准确识别MBTI类型和特征
2. **行为分析**：基于答题模式分析决策特点
3. **职业建议**：提供2-3个最适配的职业方向
4. **发展建议**：给出3-4条具体的成长建议

输出格式：标准Markdown，包含标题、段落、列表等基本元素。"""

    @staticmethod
    def get_follow_up_prompt() -> str:
        """获取后续分析Prompt"""
        return """基于之前的MBTI分析报告，请针对用户的具体问题提供深入解答。

回答要求：
1. **针对性**：直接回答用户的问题，不偏离主题
2. **深度分析**：结合MBTI理论和用户数据进行深度解读
3. **实用建议**：提供具体可行的解决方案
4. **专业性**：保持心理咨询师的专业视角

输出格式：Markdown格式，保持对话的自然流畅。"""

    @staticmethod
    def validate_mbti_data(mbti_data: str) -> bool:
        """验证MBTI数据格式"""
        required_elements = [
            "本人MBTI测试结果",
            "本人答题过程",
            "测试统计信息",
            "MBTI类型"
        ]

        return all(element in mbti_data for element in required_elements)